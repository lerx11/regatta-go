// upperOpen — верхняя граница для последней ступени: всё, что выше 63 узлов.
// Конечное число, а не math.Inf, потому что шкала уезжает в JSON-ответ API.
const upperOpen = 200.0

// FromKnots возвращает ступень шкалы Бофорта для скорости ветра в узлах.
// Отрицательные значения трактуются как штиль.
func FromKnots(knots float64) Beaufort {
	if knots < 0 || math.IsNaN(knots) {
		knots = 0
	}
	for _, b := range Scale {
		if knots < b.UpperKnots {
			return b
		}
	}
	return Scale[len(Scale)-1]
}

