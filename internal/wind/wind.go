// KnotsPerMS — коэффициент перевода м/с в узлы.
const KnotsPerMS = 1.943844

// KnotsFromMS переводит скорость из м/с в узлы.
func KnotsFromMS(ms float64) float64 { return ms * KnotsPerMS }

// KnotsFromKmh переводит скорость из км/ч в узлы.
func KnotsFromKmh(kmh float64) float64 { return kmh / 1.852 }

// Beaufort — ступень шкалы Бофорта, адаптированная под парусную практику.
type Beaufort struct {
	Scale       int     `json:"scale"`        // баллы 0..12
	Name        string  `json:"name"`         // название ступени
	Range       string  `json:"range"`        // диапазон в узлах для показа
	SeaState    string  `json:"sea_state"`    // состояние поверхности воды
	UpperKnots  float64 `json:"upper_knots"`  // верхняя граница ступени в узлах
	SailAdvice  string  `json:"sail_advice"`  // что делать с парусами
	SailorLevel string  `json:"sailor_level"` // требуемый уровень экипажа
	Status      string  `json:"status"`       // calm | ok | good | caution | danger | closed
}

